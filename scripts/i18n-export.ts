/**
 * i18n:export. Writes every string pair to docs/bangla-strings-review.md so a
 * fluent reviewer can check the Bangla (docs/ is local only, never committed):
 * how to review, then one section per area (suite apps, shell, shared), each
 * a table of key, English and Bangla.
 */
import { writeFileSync } from "node:fs"

import { bnFlat, enFlat } from "./i18n-lib"

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ")

/** Section titles by the key's first segment, in the order the reviewer reads them. */
const AREAS: [string, string][] = [
  ["brand", "Brand and product"],
  ["suites", "Suites"],
  ["apps", "App names"],
  ["common", "Common words"],
  ["status", "Statuses"],
  ["units", "Units of measure"],
  ["colours", "Vehicle colours"],
  ["shell", "Shell: top bar, sidebar, search, bell"],
  ["login", "Sign-in screen"],
  ["approvals", "Approvals inbox"],
  ["shared", "Shared screen parts (tables, pickers, print headers)"],
  ["demo", "Demo: launcher, Demo panel, scenarios, cue cards"],
  ["events", "Event stream"],
  ["consumers", "Event stream: which apps an event touched"],
  ["comms", "SMS and email texts"],
  ["rules", "Rule messages (why an action was refused)"],
  ["dashboard", "Executive dashboard and role homes"],
  ["fa", "FA Core Accounting"],
  ["ap", "AP Accounts Payable"],
  ["ar", "AR Accounts Receivable"],
  ["cab", "CAB Cash & Bank Management"],
  ["par", "PAR Party Management"],
  ["frs", "FRS Financial Reporting"],
  ["stl", "STL Sales Transaction Lifecycle"],
  ["si", "SI Sale Invoice"],
  ["pc", "PC Product Configuration"],
  ["sd", "SD Sale Delivery"],
  ["ptl", "PTL Purchase Transactions (Local)"],
  ["pm", "PM Product Master"],
  ["grn", "GRN Goods Receive Note"],
  ["st", "ST Stock Transactions"],
  ["ic", "IC Inventory Control"],
  ["irt", "IRT Reporting Tool"],
  ["reports", "Report catalogue (names, parameters, columns)"],
  ["sac", "SAC User Security"],
  ["rbac", "RBAC Role-Based Access Control"],
]

const groups = new Map<string, [string, string][]>()
for (const [key, value] of enFlat) {
  const area = key.split(".")[0]
  const list = groups.get(area) ?? []
  list.push([key, value])
  groups.set(area, list)
}
const known = new Set(AREAS.map(([area]) => area))
const order: [string, string][] = [
  ...AREAS,
  ...[...groups.keys()]
    .filter((a) => !known.has(a))
    .sort()
    .map((a): [string, string] => [a, a]),
]

const sections: string[] = []
const contents: string[] = []
for (const [area, title] of order) {
  const list = groups.get(area)
  if (!list?.length) continue
  contents.push(`- [${title}](#${area}) (${list.length})`)
  sections.push(
    `<a id="${area}"></a>`,
    `## ${title}`,
    "",
    `${list.length} strings, keys \`${area}.*\`.`,
    "",
    "| Key | English | Bangla |",
    "|---|---|---|",
    ...list.map(
      ([key, value]) =>
        `| \`${key}\` | ${esc(value)} | ${esc(bnFlat.get(key) ?? "")} |`
    ),
    ""
  )
}

const doc = [
  "# Bangla strings for review",
  "",
  `Generated by \`bun run i18n:export\` from every app's \`i18n/en.ts\` and \`i18n/bn.ts\`. ${enFlat.size} strings.`,
  "",
  "## How to review",
  "",
  "- Read the Bangla column for meaning, tone and the usual accounting and workshop words in Bangladesh. The English column is the source.",
  "- Keep `{placeholders}` exactly as they are (the app fills them in: names, numbers, dates, amounts).",
  "- Keep identifiers in Latin letters and digits: document numbers (INV-, PO-, GRN-, MR-), SKUs, app codes (FA, SI, IC), Mushak form numbers, vehicle registrations in documents.",
  "- Product and company names (UVTR_OmniflowERP, UVTR Infotech, bKash, Nagad) stay as they are.",
  "- Mark a change in the Bangla cell and send the file back; the strings are then updated in the code.",
  "",
  "## Contents",
  "",
  ...contents,
  "",
  ...sections,
].join("\n")
writeFileSync("docs/bangla-strings-review.md", doc)
console.log(
  `Wrote docs/bangla-strings-review.md (${enFlat.size} strings in ${contents.length} sections)`
)
